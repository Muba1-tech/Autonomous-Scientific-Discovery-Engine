def generate_pdf(report_md):
    # Strip emojis/special unicode to ensure standard xhtml2pdf font compatibility
    safe_md = report_md.encode('ascii', 'ignore').decode('ascii')
    html_content = markdown.markdown(safe_md, extensions=['tables'])
    
    styled_html = f"""
    <html>
        <head>
            <style>
                body {{ font-family: Helvetica, Arial, sans-serif; font-size: 14px; line-height: 1.6; color: #333; }}
                h1, h2, h3 {{ color: #2c3e50; border-bottom: 1px solid #eee; padding-bottom: 5px; }}
            </style>
        </head>
        <body>{html_content}</body>
    </html>
    """
    pdf_buffer = io.BytesIO()
    pisa.CreatePDF(styled_html, dest=pdf_buffer)
    return pdf_buffer.getvalue()

def generate_pptx(domain, query, gaps, hypothesis, scores, kg_image_bytes=None):
    template_path = os.path.join(os.path.dirname(__file__), "template.pptx")
    if os.path.exists(template_path):
        prs = Presentation(template_path)
    else:
        prs = Presentation()
    
    # Title Slide
    slide = prs.slides.add_slide(prs.slide_layouts[0])
    slide.shapes.title.text = "Autonomous Multi-Agent Discovery Report"
    slide.placeholders[1].text = f"Domain: {domain}\nGoal: {query}"
    
    # Gaps Slide
    slide = prs.slides.add_slide(prs.slide_layouts[1])
    slide.shapes.title.text = "Identified Research Gaps"
    slide.placeholders[1].text_frame.text = str(gaps)
    
    # Hypothesis Slide
    slide = prs.slides.add_slide(prs.slide_layouts[1])
    slide.shapes.title.text = "Generated Hypothesis"
    slide.placeholders[1].text_frame.text = str(hypothesis)
    
    # Metrics Slide
    slide = prs.slides.add_slide(prs.slide_layouts[1])
    slide.shapes.title.text = "Evaluation Metrics"
    tf = slide.placeholders[1].text_frame
    tf.text = f"Total Score: {scores.get('total_score', 0)}"
    tf.add_paragraph().text = f"Innovation Score: {scores.get('innovation', 0)}"
    tf.add_paragraph().text = f"Feasibility Score: {scores.get('feasibility', 0)}"
    tf.add_paragraph().text = f"Risk Factor: {scores.get('risk', 0)}"
    tf.add_paragraph().text = f"Causal Validity: {scores.get('causal_validity', 0)}"
    
    # Knowledge Graph Slide
    if kg_image_bytes:
        slide = prs.slides.add_slide(prs.slide_layouts[6]) # Typically a blank layout
        image_stream = io.BytesIO(kg_image_bytes)
        # Add picture (left, top, width) - height is auto-scaled
        slide.shapes.add_picture(image_stream, Inches(1), Inches(1), width=Inches(8))

    pptx_buffer = io.BytesIO()
    prs.save(pptx_buffer)
    return pptx_buffer.getvalue()

