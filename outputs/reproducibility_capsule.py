"""
AION X 2.0 — Reproducibility Capsule Generator
Packages an autonomous research discovery into an immutable, self-contained reproducibility bundle (.zip):
- README.md: Execution instructions & discovery metadata
- manifest.json: Cryptographic SHA-256 hashes of all components
- environment.yml & requirements.txt: Pinned dependencies
- experiment_protocol.py: Executable sandboxed experiment code with deterministic seeds
- reproduce.py: One-click local reproduction runner
- provenance_graph.json: Complete evidence lineage trace
- scientific_report.md: Full 20-section formal report
"""

import os
import io
import zipfile
import json
import hashlib
import datetime
from typing import Dict, Any, List, Optional


class ReproducibilityCapsuleGenerator:
    """Generates standalone Reproducibility Capsule ZIP bundles."""

    @classmethod
    def generate_capsule(
        cls,
        mission_id: str,
        research_goal: str,
        hypothesis_dict: Dict[str, Any],
        experiment_code: str,
        report_markdown: str,
        provenance_json: Optional[str] = None
    ) -> bytes:
        """
        Creates an in-memory ZIP archive containing the full reproducibility capsule.
        """
        zip_buffer = io.BytesIO()
        hyp_id = hypothesis_dict.get('id', 'H-001')
        timestamp = datetime.datetime.utcnow().isoformat()

        with zipfile.ZipFile(zip_buffer, "w", zipfile.ZIP_DEFLATED) as zf:
            # 1. README.md
            readme_content = f"""# AION X 2.0 — Autonomous Scientific Discovery Capsule
**Mission ID**: `{mission_id}`  
**Hypothesis ID**: `{hyp_id}`  
**Generated At**: `{timestamp}`  
**Research Objective**: {research_goal}

---

## 🔁 How to Reproduce This Discovery
1. Ensure Python 3.9+ is installed.
2. Install dependencies:
   ```bash
   pip install -r requirements.txt
   ```
3. Run the one-click replication script:
   ```bash
   python reproduce.py
   ```
4. Verify that generated statistics match `manifest.json` SHA-256 signatures.

---
*Generated by AION X 2.0 — Autonomous Scientific Discovery & Falsification Operating System.*
"""
            zf.writestr("README.md", readme_content)

            # 2. requirements.txt & environment.yml
            reqs = "numpy>=1.23.0\nscipy>=1.9.0\npandas>=1.5.0\nscikit-learn>=1.1.0\nmatplotlib>=3.6.0\nnetworkx>=2.8.0\n"
            zf.writestr("requirements.txt", reqs)

            env_yml = f"""name: aion-capsule-{mission_id.lower()}
channels:
  - conda-forge
  - defaults
dependencies:
  - python=3.10
  - numpy>=1.23.0
  - scipy>=1.9.0
  - pandas>=1.5.0
  - scikit-learn>=1.1.0
  - matplotlib>=3.6.0
  - networkx>=2.8.0
"""
            zf.writestr("environment.yml", env_yml)

            # 3. experiment_protocol.py
            zf.writestr("experiment_protocol.py", experiment_code)

            # 4. reproduce.py
            reproduce_script = f"""# AION X 2.0 Local Reproduction Runner
import subprocess
import sys
import json

print("="*60)
print("AION X 2.0 — Executing Autonomous Discovery Reproduction")
print("Mission: {mission_id} | Hypothesis: {hyp_id}")
print("="*60)

res = subprocess.run([sys.executable, "experiment_protocol.py"], capture_output=True, text=True)
if res.returncode == 0:
    print("\\n[SUCCESS] Experiment protocol executed cleanly.")
    print("\\nOutput Metrics:")
    print(res.stdout)
else:
    print("\\n[FAILURE] Execution error encountered:")
    print(res.stderr)
"""
            zf.writestr("reproduce.py", reproduce_script)

            # 5. provenance_graph.json
            prov = provenance_json or json.dumps({"mission_id": mission_id, "nodes": [], "edges": []}, indent=2)
            zf.writestr("provenance_graph.json", prov)

            # 6. scientific_report.md
            zf.writestr("scientific_report.md", report_markdown)

            # 7. manifest.json with SHA-256 hashes
            manifest = {
                "capsule_version": "2.0.0",
                "mission_id": mission_id,
                "hypothesis_id": hyp_id,
                "created_at": timestamp,
                "files": {
                    "README.md": hashlib.sha256(readme_content.encode()).hexdigest(),
                    "requirements.txt": hashlib.sha256(reqs.encode()).hexdigest(),
                    "environment.yml": hashlib.sha256(env_yml.encode()).hexdigest(),
                    "experiment_protocol.py": hashlib.sha256(experiment_code.encode()).hexdigest(),
                    "reproduce.py": hashlib.sha256(reproduce_script.encode()).hexdigest(),
                    "provenance_graph.json": hashlib.sha256(prov.encode()).hexdigest(),
                    "scientific_report.md": hashlib.sha256(report_markdown.encode()).hexdigest()
                }
            }
            zf.writestr("manifest.json", json.dumps(manifest, indent=2))

        zip_buffer.seek(0)
        return zip_buffer.getvalue()
